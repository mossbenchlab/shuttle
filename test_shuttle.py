def t_set(n):
    s3 = SH.Store(SH.Schema("table items key id : id:int qty:int")); s3.load({"items": [{"id": i, "qty": 0} for i in range(n)]})
    best = 1e9
    for k in range(5):
        t0 = time.perf_counter(); assert s3.execute(f"set items where id={n-1-k} : qty=1").startswith("ok"); best = min(best, time.perf_counter() - t0)
    return best
